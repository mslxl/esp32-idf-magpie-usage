const dictionaries: Record<Language, Record<MessageKey, string>> = { en, zh };

export function translate(language: Language, key: MessageKey, params: Params = {}): string {
  return dictionaries[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]));
}

export const LANGUAGE_STORAGE_KEY = "magpie-usage.language";

export function loadLanguage(storage: Pick<Storage, "getItem"> | undefined): Language {
  try {
    return storage?.getItem(LANGUAGE_STORAGE_KEY) === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}

export function saveLanguage(storage: Pick<Storage, "setItem"> | undefined, language: Language): void {
  try { storage?.setItem(LANGUAGE_STORAGE_KEY, language); } catch { /* private mode: keep the in-memory choice */ }
}

