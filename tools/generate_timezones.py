"""Generate the supported IANA transition table using pinned tzdata 2026.2.

Run: uv run --with tzdata==2026.2 python -I tools/generate_timezones.py
The checked-in output covers UTC years 2000 through 2100 (exclusive).
"""
from datetime import datetime, timezone
from importlib.resources import files
from pathlib import Path
from zoneinfo import ZoneInfo
import json
import tzdata

ROOT = Path(__file__).resolve().parents[1]
ZONES = ["UTC", "Etc/UTC", "Asia/Shanghai", "Asia/Hong_Kong", "Asia/Taipei", "Asia/Tokyo",
         "Asia/Singapore", "Asia/Kolkata", "Europe/London", "Europe/Berlin", "Europe/Paris",
         "America/New_York", "America/Chicago", "America/Denver", "America/Los_Angeles",
         "Australia/Sydney", "Pacific/Auckland"]
START, END = 946684800, 4102444800
assert tzdata.__version__ == "2026.2", tzdata.__version__
result = {}
for name in ZONES:
    with files("tzdata.zoneinfo").joinpath(*name.split("/")).open("rb") as stream:
        zone = ZoneInfo.from_file(stream, key=name)
    def offset(epoch):
        return int(datetime.fromtimestamp(epoch, timezone.utc).astimezone(zone).utcoffset().total_seconds())
    previous = offset(START)
    changes = [[START, previous]]
    cursor = START
    while cursor < END:
        next_epoch = min(cursor + 86400, END)
        current = offset(next_epoch)
        if current != previous:
            lo, hi = cursor, next_epoch
            while hi - lo > 1:
                middle = (lo + hi) // 2
                if offset(middle) == previous:
                    lo = middle
                else:
                    hi = middle
            changes.append([hi, current])
            previous = current
        cursor = next_epoch
    result[name] = changes
output = "// Generated by tools/generate_timezones.py from IANA tzdata 2026.2.\n"
output += "export const TIMEZONE_VERSION = '2026.2';\n"
output += f"export const TIMEZONE_START = {START}, TIMEZONE_END = {END};\n"
output += "export const TIMEZONE_TRANSITIONS: Record<string, readonly (readonly [number, number])[]> = "
output += json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n"
(ROOT / "timezone-data.ts").write_text(output, encoding="utf-8")
(ROOT / "supported-timezones.ts").write_text(
    "// Generated by tools/generate_timezones.py from IANA tzdata 2026.2.\n"
    + "export const SUPPORTED_TIMEZONES = " + json.dumps(ZONES) + " as const;\n", encoding="utf-8")
(ROOT / "main" / "supported_timezones.inc").write_text(
    "/* Generated by tools/generate_timezones.py from IANA tzdata 2026.2. */\n"
    + ",\n".join(json.dumps(zone) for zone in ["", *ZONES]) + "\n", encoding="utf-8")
print(f"Generated {len(result)} zones / {sum(map(len, result.values()))} transitions")
